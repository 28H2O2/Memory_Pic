/**
 * 通过经纬度查找最近的城市
 * @param {number} lat 纬度
 * @param {number} lng 经度
 * @returns {string|null} 城市名称，如 "广东·深圳"
 */
function reverseGeocode(lat, lng) {
  if (!lat || !lng || isNaN(lat) || isNaN(lng)) return null;

  let minDist = Infinity;
  let nearest = null;

  for (const [name, cLat, cLng] of CITIES) {
    // 使用简化的球面距离（对精确到地级市够用）
    const dLat = (lat - cLat) * Math.PI / 180;
    const dLng = (lng - cLng) * Math.PI / 180;
    const a = Math.sin(dLat / 2) ** 2
      + Math.cos(lat * Math.PI / 180) * Math.cos(cLat * Math.PI / 180)
      * Math.sin(dLng / 2) ** 2;
    const dist = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));

    if (dist < minDist) {
      minDist = dist;
      nearest = name;
    }
  }

  // 如果最近城市距离超过 300km，可能不在已知城市范围内
  const distKm = minDist * 6371;
  if (distKm > 300) return null;

  return nearest;
}

